// Builds dist/ from src/: token files (CSS, SCSS, JS), the bundled stylesheets, and copies of the
// fonts, icons and brand images. No dependencies; run with `npm run build`.
//
// dist/ is committed, because tools install this package straight from GitHub and npm doesn't
// build git dependencies reliably. `npm run check` fails if dist/ is out of date.

import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src');
const dist = join(root, 'dist');

const HEADER = '/* Generated by scripts/build.mjs from src/. Do not edit; edit src/ and run `npm run build`. */\n';

// Order matters only where components build on each other (modal extends panel).
const COMPONENTS = [
  'typography', 'top-bar', 'panel', 'panel-message', 'data-list', 'button', 'button-group', 'fields',
  'object-list', 'map-layer', 'modal', 'small-print', 'layout',
];

const tokens = JSON.parse(readFileSync(join(src, 'tokens.json'), 'utf8'));

/** Colour tokens keep their Figma names (--paddock-green, --text-primary); the rest get their group as a prefix (--space-16). */
const UNPREFIXED_GROUPS = ['color', 'neutral', 'semantic'];

function tokenName(group, key) {
  return UNPREFIXED_GROUPS.includes(group) ? key : `${group}-${key}`;
}

/**
 * Every token as { group, name, value, cssValue, note }. An alias token's cssValue is var(--other), so
 * overriding a colour in a tool also changes the aliases that point at it; value is always resolved.
 */
function tokenEntries() {
  const raw = new Map();
  for (const [group, values] of Object.entries(tokens)) {
    if (group.startsWith('$')) continue;
    for (const [key, token] of Object.entries(values)) raw.set(tokenName(group, key), { group, token });
  }

  function resolve(name, seen = []) {
    const entry = raw.get(name);
    if (!entry) throw new Error(`Unknown token alias: ${[...seen, name].join(' -> ')}`);
    if (seen.includes(name)) throw new Error(`Circular token alias: ${[...seen, name].join(' -> ')}`);
    const { alias, value } = entry.token;
    return alias ? resolve(alias, [...seen, name]) : value;
  }

  return [...raw].map(([name, { group, token }]) => {
    const notes = [token.figma && `Figma: ${token.figma}`, token.role, token.deprecated && `Deprecated: ${token.deprecated}`];
    return {
      group,
      name,
      value: resolve(name),
      cssValue: token.alias ? `var(--${token.alias})` : token.value,
      note: notes.filter(Boolean).join('. '),
    };
  });
}

function camelCase(name) {
  return name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
}

function buildTokens() {
  const entries = tokenEntries();

  const css = entries.map(({ name, cssValue, note }) => `  --${name}: ${cssValue};${note ? ` /* ${note} */` : ''}`);
  writeFileSync(join(dist, 'tokens.css'), `${HEADER}:root {\n${css.join('\n')}\n}\n`);

  // SCSS variables hold the raw values, so Sass functions like color.adjust() work on them.
  const scss = entries.map(({ name, value }) => `$${name}: ${value};`);
  writeFileSync(join(dist, 'tokens.scss'), `${HEADER.replace('/*', '//').replace(' */', '')}${scss.join('\n')}\n`);

  // JS: grouped object, e.g. tokens.color.paddockGreen, tokens.space[16].
  const grouped = {};
  for (const { group, name, value } of entries) {
    const key = camelCase(UNPREFIXED_GROUPS.includes(group) ? name : name.replace(`${group}-`, ''));
    (grouped[camelCase(group)] ??= {})[key] = value;
  }
  const json = JSON.stringify(grouped, null, 2);
  writeFileSync(join(dist, 'tokens.js'), `${HEADER}export const tokens = ${json};\n\nexport default tokens;\n`);
  writeFileSync(
    join(dist, 'tokens.d.ts'),
    `${HEADER}export declare const tokens: ${json.replace(/: "[^"]*"/g, ': string')};\n\nexport default tokens;\n`,
  );
}

function read(path) {
  return readFileSync(join(src, path), 'utf8').trim();
}

function buildCss() {
  const fonts = read('fonts.css');
  const base = read('base.css');
  const components = COMPONENTS.map((name) => read(`components/${name}.css`)).join('\n\n');
  const tokensCss = readFileSync(join(dist, 'tokens.css'), 'utf8').replace(HEADER, '').trim();

  writeFileSync(join(dist, 'fonts.css'), `${HEADER}${fonts}\n`);
  writeFileSync(join(dist, 'base.css'), `${HEADER}${base}\n`);
  writeFileSync(join(dist, 'components.css'), `${HEADER}${components}\n`);
  writeFileSync(join(dist, 'geeta.css'), `${HEADER}${[fonts, tokensCss, base, components].join('\n\n')}\n`);
}

function checkComponentsListed() {
  const files = readdirSync(join(src, 'components')).map((f) => f.replace(/\.css$/, ''));
  const missing = files.filter((f) => !COMPONENTS.includes(f));
  if (missing.length > 0) {
    throw new Error(`Add these to COMPONENTS in scripts/build.mjs: ${missing.join(', ')}`);
  }
}

checkComponentsListed();
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist);
for (const folder of ['fonts', 'icons', 'brand']) {
  cpSync(join(src, folder), join(dist, folder), { recursive: true });
}
buildTokens();
buildCss();
console.log('Built dist/');
